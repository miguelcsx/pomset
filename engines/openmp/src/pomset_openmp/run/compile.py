"""Compile a kernel and the driver that exercises it.

The kernel is handed to the compiler exactly as the user wrote it; nothing here
reads it as text or rewrites it. What comes back is the compiler's own
diagnostics, recorded as they are.

Compilation is artifact evidence. A program that builds has established nothing
about what it does, which is why a build failure is reported as an unsupported
result rather than as a verdict on the kernel.

The calling convention, which is this harness's and not the contract's:

    void <symbol>(<each declared allocation as a pointer, in declaration order>,
                  <each numeric domain variable as a scalar, in declaration order>);

One driver is generated per domain point with that point's values and buffer
sizes written into it. Nothing is computed by the driver: the extents come from
the same evaluator the comparison uses, rather than from a second opinion written
in C that could disagree with it.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from pomset_contracts.engine_protocol import InputInvalid, Unsupported, command

from .buffers import TYPES, input_expression, poison_literal

COMPILER = "clang"
TIMEOUT_SECONDS = 120.0

# The declared widths, as the scalar types a C kernel can receive.
SCALAR_TYPES = {
    "i32": "int",
    "u32": "unsigned int",
    "i64": "long long",
    "u64": "unsigned long long",
}

DRIVER = """/* Generated by pomset_openmp.run.compile. Do not edit. */
#include <stdio.h>
#include <stdlib.h>

{prototype}

int main(void) {{
{declarations}
{fill}
{poison}
  {call};
{dump}
  return 0;
}}
"""


def c_type(dtype: str) -> str:
    entry = TYPES.get(dtype)
    if entry is None:
        raise Unsupported(f"allocation dtype {dtype}", 1, 0)
    return str(entry["c"])


def scalar_type(variable: dict) -> str:
    """The C type of one domain variable, or a refusal naming what it is."""
    if variable.get("type") != "int":
        raise Unsupported(
            f"domain variable {variable['name']} of type {variable.get('type')}", 1, 0
        )
    width = variable.get("width", "i32")
    if width not in SCALAR_TYPES:
        raise Unsupported(f"domain variable width {width}", 1, 0)
    return SCALAR_TYPES[width]


def _prototype(symbol: str, allocations: list[dict], variables: list[dict]) -> str:
    parameters = [f"{c_type(item['dtype'])} *{item['name']}" for item in allocations]
    parameters += [f"{scalar_type(item)} {item['name']}" for item in variables]
    return f"void {symbol}({', '.join(parameters)});"


def driver_source(
    symbol: str,
    allocations: list[dict],
    variables: list[dict],
    extents: dict[str, int],
    values: dict[str, int],
) -> str:
    """The program that runs one domain point and prints what the kernel wrote."""
    declarations = [
        f"  {c_type(item['dtype'])} *{item['name']} = "
        f"malloc(sizeof({c_type(item['dtype'])}) * {extents[item['name']]});"
        for item in allocations
    ]
    fill = [
        f"  for (long long i = 0; i < {extents[item['name']]}; ++i) "
        f"{item['name']}[i] = {input_expression(item['dtype'], 'i')};"
        for item in allocations
        if item["role"] == "input"
    ]
    poison = [
        f"  for (long long i = 0; i < {extents[item['name']]}; ++i) "
        f"{item['name']}[i] = {poison_literal(item['dtype'])};"
        for item in allocations
        if item["role"] != "input"
    ]
    dump = [
        f"  for (long long i = 0; i < {extents[item['name']]}; ++i) "
        f'printf("{TYPES[item["dtype"]]["printf"]}\\n", '
        f"{_print_value(item['dtype'], item['name'])});"
        for item in allocations
        if item["role"] == "output"
    ]
    arguments = [item["name"] for item in allocations] + [
        f"{values[item['name']]}" for item in variables
    ]
    return DRIVER.format(
        prototype=_prototype(symbol, allocations, variables),
        declarations="\n".join(declarations),
        fill="\n".join(fill),
        poison="\n".join(poison),
        call=f"{symbol}({', '.join(arguments)})",
        dump="\n".join(dump),
    )


def _print_value(dtype: str, name: str) -> str:
    if TYPES[dtype]["kind"] == "float":
        return f"(double){name}[i]"
    return f"(long long){name}[i]"


def ensure_compiler() -> str:
    found = shutil.which(COMPILER)
    if found is None:
        raise InputInvalid(f"{COMPILER} is not installed, so no kernel can be built")
    return found


def build(directory: Path, sources: list[Path], driver: str) -> tuple[dict, Path]:
    """Compiles the user's sources together with the generated driver."""
    ensure_compiler()
    directory.mkdir(parents=True, exist_ok=True)
    driver_path = directory / "driver.c"
    driver_path.write_text(driver, encoding="utf-8")
    binary = directory / "kernel"
    result = command(
        [
            COMPILER,
            "-fopenmp",
            "-g",
            "-O1",
            *[str(path) for path in sources],
            str(driver_path),
            "-o",
            str(binary),
            "-lm",
        ],
        TIMEOUT_SECONDS,
    )
    return result, binary
